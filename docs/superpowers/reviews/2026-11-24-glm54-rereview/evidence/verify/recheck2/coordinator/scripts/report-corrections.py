def main():
    s = open(P).read()
    before = s.split('\n')
    bad = 0
    for ln, old, new in PAIRS:
        hits = [i + 1 for i, l in enumerate(before) if old in l]
        n = s.count(old)
        ok = n == 1 and hits == [ln]
        bad += not ok
        print(f'  L{ln:<4d} {"ok  " if ok else "MISS"} 命中 {n} 次，行 {hits}')
        if ok:
            s = s.replace(old, new)
    after = s.split('\n')
    same_lines = len(after) == len(before)
    print(f'行数 前/后 = {len(before)} / {len(after)}（须相同）')
    if bad or not same_lines:
        print('有不符，未写入')
        return 1
    if '--apply' in sys.argv:
        open(P, 'w').write(s)
        print('已写入 report.md（工作区改动，未提交）')
    else:
        print('演练结束，未写入')
    return 0


